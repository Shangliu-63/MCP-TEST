def build_database() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    if DB_PATH.exists():
        DB_PATH.unlink()

    connection = sqlite3.connect(DB_PATH)
    try:
        connection.execute("PRAGMA foreign_keys = ON")
        connection.executescript(SCHEMA_PATH.read_text(encoding="utf-8"))
        connection.executemany(
            "INSERT INTO departments VALUES (?, ?, ?, ?, ?)", DEPARTMENTS
        )
        connection.executemany(
            "INSERT INTO people VALUES (?, ?, ?, ?, ?, ?)", PEOPLE
        )

        responsibilities = []
        sequence = 1
        department_by_person = {row[0]: row[4] for row in PEOPLE}
        for person_id, entries in RESPONSIBILITY_DATA.items():
            for description, keywords in entries:
                responsibilities.append(
                    (f"R{sequence:03d}", department_by_person[person_id], person_id, description, keywords, 3, 1)
                )
                sequence += 1
        connection.executemany(
            "INSERT INTO responsibilities VALUES (?, ?, ?, ?, ?, ?, ?)",
            responsibilities,
        )

        connection.executemany(
            """
            INSERT INTO test_documents (
                id, subject, body, expected_primary_department_id,
                expected_primary_person_id, expected_cc_department_ids,
                difficulty, notes
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            [(*row[:5], json.dumps(row[5], ensure_ascii=False), *row[6:]) for row in TEST_DOCUMENTS],
        )
        connection.executemany(
            """
            INSERT INTO dispatch_history (
                document_subject, document_summary, primary_department_id,
                primary_person_id, cc_department_ids, accepted
            ) VALUES (?, ?, ?, ?, ?, ?)
            """,
            [(*row[:4], json.dumps(row[4], ensure_ascii=False), row[5]) for row in HISTORY],
        )
        connection.commit()

        problems = connection.execute("PRAGMA foreign_key_check").fetchall()
        if problems:
            raise RuntimeError(f"Foreign key validation failed: {problems}")
    finally:
        connection.close()


if __name__ == "__main__":
    build_database()
    print(f"Created {DB_PATH}")
